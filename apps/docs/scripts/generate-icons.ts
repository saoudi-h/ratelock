/**
 * Bundles the Iconify icons the site uses.
 *
 * `@iconify/react` fetches missing icons from api.iconify.design at runtime:
 * one request per collection, icons that pop in late, layout shifts and a
 * third-party dependency on the critical path. This script scans the source
 * for `prefix:name` icon ids and writes them to `src/generated/icons.ts`,
 * which registers them synchronously so they render in the prerendered HTML.
 *
 * Run it after adding or renaming an icon: `pnpm generate:icons`.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import type { IconifyJSON } from '@iconify/types'
import { getIcons } from '@iconify/utils'

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const srcDir = path.join(appRoot, 'src')
const outDir = path.join(srcDir, 'generated')
const require = createRequire(import.meta.url)

const prefixes = [
    'bxl',
    'devicon',
    'devicon-plain',
    'logos',
    'lucide',
    'mdi',
    'simple-icons',
    'solar',
    'thesvg-color',
]

function* walk(dir: string): Generator<string> {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name)
        if (entry.isDirectory()) {
            if (entry.name !== 'generated') yield* walk(full)
        } else if (/\.(tsx?|mdx?)$/.test(entry.name)) {
            yield full
        }
    }
}

/**
 * Icons are split in two modules. The sections below the fold are loaded
 * after the page is idle (see `lazyWhenIdle`), so their icons ship with that
 * code instead of weighing on the first load.
 */
const deferredFiles = [
    /components\/home\/sections\/(features|engines|integrations|performance)\//,
    /components\/home\/sections\/simulation-section/,
    /components\/home\/components\//,
]
type Group = 'core' | 'deferred'

const pattern = new RegExp(`['"\`](${prefixes.join('|')}):([a-z0-9]+(?:-[a-z0-9]+)*)['"\`]`, 'g')
const used: Record<Group, Map<string, Set<string>>> = { core: new Map(), deferred: new Map() }

for (const file of walk(srcDir)) {
    const group: Group = deferredFiles.some(regex => regex.test(file)) ? 'deferred' : 'core'
    for (const match of readFileSync(file, 'utf8').matchAll(pattern)) {
        const [, prefix, name] = match
        if (!prefix || !name) continue
        const map = used[group]
        if (!map.has(prefix)) map.set(prefix, new Set())
        map.get(prefix)?.add(name)
    }
}

mkdirSync(outDir, { recursive: true })

for (const group of ['core', 'deferred'] as const) {
    const collections: IconifyJSON[] = []
    for (const prefix of [...used[group].keys()].sort()) {
        const names = [...(used[group].get(prefix) ?? [])].sort()
        const data = JSON.parse(
            readFileSync(require.resolve(`@iconify-json/${prefix}/icons.json`), 'utf8')
        ) as IconifyJSON
        const subset = getIcons(data, names)
        if (!subset) throw new Error(`No icons found for ${prefix}`)
        const missing = names.filter(
            name => !(name in subset.icons) && !(name in (subset.aliases ?? {}))
        )
        if (missing.length > 0) throw new Error(`Missing ${prefix} icons: ${missing.join(', ')}`)
        collections.push(subset)
    }

    writeFileSync(
        path.join(outDir, `icons-${group}.ts`),
        `// Generated by scripts/generate-icons.ts. Do not edit.
import { addCollection } from '@iconify/react'

${collections.map(collection => `addCollection(${JSON.stringify(collection)})`).join('\n')}
`
    )
    const count = [...used[group].values()].reduce((sum, set) => sum + set.size, 0)
    console.log(`icons-${group}.ts: ${count} icons from ${used[group].size} collections.`)
}
